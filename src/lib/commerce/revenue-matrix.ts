const CSV_COLUMNS: (keyof MatrixRow)[] = ["feature", "routes", "problem", "audience", "value", "access", "monetization", "journey", "dependencies", "operatingCost", "risks", "metrics", "priority", "status"];

export function matrixToCsv(rows: MatrixRow[] = REVENUE_MATRIX): string {
  const cell = (v: string) => (/[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);
  return [CSV_COLUMNS.join(","), ...rows.map((r) => CSV_COLUMNS.map((c) => cell(r[c])).join(","))].join("\r\n") + "\r\n";
}
