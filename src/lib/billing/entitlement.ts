import { createHmac, timingSafeEqual } from "node:crypto";

/**
 * Premium entitlement token, stored in a signed httpOnly cookie.
 *
 * Until accounts exist, the cookie is the trusted record that this browser holds an active
 * subscription. It carries the Stripe customer and subscription ids and expires at the end of
 * the paid period; after that the server re-checks the subscription with Stripe before
 * renewing it, so a cancellation takes effect at period end. The client can read its plan from
 * /api/billing/entitlement but can never mint or edit the token.
 */

export const ENTITLEMENT_COOKIE = "nw_ent";

export interface Entitlement {
  plan: "premium";
  cus: string;
  sub: string;
  /** Unix seconds: when the server must re-check the subscription with Stripe. */
  exp: number;
  cancelAtPeriodEnd?: boolean;
  trial?: boolean;
  /** The latest renewal payment failed; Stripe is retrying. */
  pastDue?: boolean;
}

const b64 = (s: string) => Buffer.from(s).toString("base64url");
const unb64 = (s: string) => Buffer.from(s, "base64url").toString("utf8");
const mac = (data: string, secret: string) => createHmac("sha256", secret).update(data).digest("base64url");

function safeEqual(a: string, b: string) {
  const x = Buffer.from(a);
  const y = Buffer.from(b);
  return x.length === y.length && timingSafeEqual(x, y);
}

export function signEntitlement(e: Entitlement, secret: string): string {
  const body = b64(JSON.stringify(e));
  return `${body}.${mac(`ent.${body}`, secret)}`;
}

export type VerifyResult = { valid: true; entitlement: Entitlement; expired: boolean } | { valid: false };

/** Checks the signature. An expired-but-authentic token is reported so the server can re-check Stripe. */
export function verifyEntitlement(token: string | undefined, secret: string, nowSec = Math.floor(Date.now() / 1000)): VerifyResult {
  if (!token) return { valid: false };
  const [body, sig] = token.split(".");
  if (!body || !sig || !safeEqual(sig, mac(`ent.${body}`, secret))) return { valid: false };
  try {
    const e = JSON.parse(unb64(body)) as Entitlement;
    if (e.plan !== "premium" || typeof e.cus !== "string" || typeof e.sub !== "string" || typeof e.exp !== "number") return { valid: false };
    return { valid: true, entitlement: e, expired: e.exp <= nowSec };
  } catch {
    return { valid: false };
  }
}

/** Signed payment link for a verified directory listing, generated by an admin. */
export function signListing(listing: string, secret: string) {
  return mac(`listing.${listing}`, secret);
}

export function verifyListing(listing: string, sig: string | undefined | null, secret: string) {
  return Boolean(sig) && /^[a-z0-9-]{2,80}$/.test(listing) && safeEqual(sig!, signListing(listing, secret));
}
